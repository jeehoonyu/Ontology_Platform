def bootstrap(database_url: str | None):
    """Import the app against a chosen database. Must precede any app import."""
    if database_url:
        os.environ["DATABASE_URL"] = database_url
    elif not os.environ.get("DATABASE_URL"):
        tmpdir = tempfile.mkdtemp(prefix="read-path-bounds-")
        os.environ["DATABASE_URL"] = f"sqlite:///{os.path.join(tmpdir, 'bounds.db')}"

    if str(REPO_ROOT / "oms") not in sys.path:
        sys.path.insert(0, str(REPO_ROOT / "oms"))
    from app import models, models_action  # noqa: E402
    from app.database import SessionLocal, engine  # noqa: E402
    from app import runtime  # noqa: E402

    models.Base.metadata.create_all(bind=engine)
    models_action.Base.metadata.create_all(bind=engine)
    return models, SessionLocal, engine, runtime


def corpus_size(models, SessionLocal) -> int:
    """Rows in the corpus, or -1 when it was built by a different fixture.

    Reuse compares a row count, and a row count cannot tell two fixtures apart.
    The version is stored on the object type so a corpus from an older
    definition is rebuilt rather than silently measured and compared against
    numbers it has no relation to.
    """
    db = SessionLocal()
    try:
        object_type = db.query(models.ObjectType).filter(
            models.ObjectType.id == TYPE_ID).first()
        if not object_type:
            return 0
        if (object_type.properties or {}).get("fixture_version") != FIXTURE_VERSION:
            return -1
        return db.query(models.ObjectInstance).filter(
            models.ObjectInstance.object_type_id == TYPE_ID).count()
    finally:
        db.close()


def seed(models, SessionLocal, engine, size: int) -> None:
    from sqlalchemy import text

    dialect = engine.dialect.name
    db = SessionLocal()
    try:
        db.query(models.ObjectInstance).filter(
            models.ObjectInstance.object_type_id == TYPE_ID
        ).delete(synchronize_session=False)
        db.query(models.ObjectType).filter(
            models.ObjectType.id == TYPE_ID
        ).delete(synchronize_session=False)
        db.commit()
        db.add(models.ObjectType(
            id=TYPE_ID, project_id="default", display_name="Read Path Asset",
            properties={
                "fixture_version": FIXTURE_VERSION,
                "assetId": {"type": "string"},
                "risk": {"type": "number"},
                "category": {"type": "string"},
                "latitude": {"type": "number"},
                "longitude": {"type": "number"},
            },
            created_at=0, updated_at=0,
        ))
        db.commit()
    finally:
        db.close()

    width = max(8, len(str(size)))
    if dialect == "postgresql":
        # Server-side generation, as benchmark_ontology_scale_postgres.py does.
        # Ten million rows through Python would dominate the run.
        with engine.begin() as connection:
            connection.execute(text("SET LOCAL synchronous_commit = off"))
            # The geo columns are populated here for the same reason the
            # migration backfills them: a Core insert bypasses the ORM listener
            # that normally maintains them, so rows would arrive marked
            # unindexed and every spatial query would take the correct-but-slow
            # scan. Seeding them mirrors what a real bulk load must do.
            # Positions are computed once per row in a subquery and reused, and
            # must stay identical to `position()` above -- the SQLite path uses
            # that, so a divergence would mean the two dialects measured
            # different corpora while reporting the same fixture version.
            connection.execute(text("""
                INSERT INTO object_instances (
                    id, project_id, object_type_id, properties, source_asset_id,
                    is_active, lineage, created_at, updated_at,
                    geo_min_lon, geo_min_lat, geo_max_lon, geo_max_lat, geo_indexed
                )
                SELECT
                    :prefix || lpad(p.series::text, :width, '0'),
                    'default', :type_id,
                    jsonb_build_object(
                        'assetId', :prefix || lpad(p.series::text, :width, '0'),
                        'risk', mod(p.series, 101),
                        'category', 'category_' || mod(p.series, 20),
                        'latitude', p.lat,
                        'longitude', p.lon
                    ),
                    NULL, true, '{}'::jsonb,
                    1700000000 + mod(p.series, 1000000),
                    1700000000 + mod(p.series, 1000000),
                    p.lon, p.lat, p.lon, p.lat,
                    true
                FROM (
                    SELECT series,
                        :west
                          + (mod(series, :sites) * :alpha_x
                             - floor(mod(series, :sites) * :alpha_x)) * :span
                          + ((series * :alpha_y - floor(series * :alpha_y)) * 2 - 1) * :spread
                          AS lon,
                        :south
                          + (mod(series, :sites) * :alpha_y
                             - floor(mod(series, :sites) * :alpha_y)) * :span
                          + ((series * :alpha_x - floor(series * :alpha_x)) * 2 - 1) * :spread
                          AS lat
                    FROM generate_series(1, :count) AS generated(series)
                ) AS p
            """), {"prefix": OBJECT_PREFIX, "width": width,
                   "type_id": TYPE_ID, "count": size,
                   "west": REGION_WEST, "south": REGION_SOUTH,
                   "span": REGION_SPAN_DEGREES, "sites": SITE_COUNT,
                   "spread": SITE_SPREAD_DEGREES,
                   "alpha_x": ALPHA_X, "alpha_y": ALPHA_Y})
        _refresh_statistics(engine)
        return

    _seed_python(models, SessionLocal, engine, size, width)
    _refresh_statistics(engine)


def _refresh_statistics(engine) -> None:
    """Update planner statistics after a bulk load.

    Not a nicety. Measured at one million objects, the identical corpus with
    stale statistics against current ones: the map viewport 6,263.3 ms versus
    10.5 ms, the radius query 6,388.0 ms versus 466.2 ms, the facet 5,610.0 ms
    versus 2,368.8 ms. With no statistics the planner estimated one row for the
    object type and chose to filter through the type index instead of the GiST
    index, so the harness was measuring what the planner did not know rather
    than what the system can do.

    Every real bulk load owes this too, which is why it belongs in the fixture
    rather than in a caveat.
    """
    from sqlalchemy import text

    with engine.begin() as connection:
        if engine.dialect.name == "postgresql":
            connection.execute(text("ANALYZE object_instances"))
        elif engine.dialect.name == "sqlite":
            connection.execute(text("ANALYZE"))


def _seed_python(models, SessionLocal, engine, size: int, width: int) -> None:
    db = SessionLocal()
    try:
        rows: List[Dict[str, Any]] = []
        for series in range(1, size + 1):
            longitude, latitude = position(series)
            rows.append({
                "id": f"{OBJECT_PREFIX}{series:0{width}d}",
                "project_id": "default",
                "object_type_id": TYPE_ID,
                "properties": {
                    "assetId": f"{OBJECT_PREFIX}{series:0{width}d}",
                    "risk": series % 101,
                    "category": f"category_{series % 20}",
                    "latitude": latitude,
                    "longitude": longitude,
                },
                "source_asset_id": None, "materialization_id": None,
                "is_active": True, "retired_at": None, "lineage": {},
                "created_at": 1700000000 + series % 1000000,
                "updated_at": 1700000000 + series % 1000000,
                "geo_min_lon": longitude, "geo_max_lon": longitude,
                "geo_min_lat": latitude, "geo_max_lat": latitude,
                "geo_indexed": True,
            })
            if len(rows) >= 20_000:
                db.execute(models.ObjectInstance.__table__.insert(), rows)
                db.commit()
                rows = []
        if rows:
            db.execute(models.ObjectInstance.__table__.insert(), rows)
        db.commit()
    finally:
        db.close()


