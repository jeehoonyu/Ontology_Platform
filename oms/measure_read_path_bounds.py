"""Measure whether object-set reads are bounded by the page or by the object type.

The Tier B ontology-scale gate reads an object set with no residual filter. No
user-facing surface issues that shape: the Object Explorer sends a filter, its
left rail aggregates facets, and the Operational Map sends a spatial predicate.
Each of those takes a path that materializes the whole object type before any
limit applies, so the gate's bounded p95 says nothing about them.

This measures the four shapes side by side at several cardinalities, in latency
and in peak resident memory, so the growth curve is measured rather than
asserted. It is the harness for condition B1 of ``docs/GOAL_2026-08-06.md``.

The fixture mirrors ``benchmark_ontology_scale_postgres.py`` -- same property
shape, same server-side ``generate_series`` seed -- so the shapes are measured
on the corpus the gate certifies rather than on a fixture of this file's own
invention. ``latitude``/``longitude`` scalars are what ``extract_geometry``
falls back to, so the spatial shape reads the same rows as the others.

Three rules, two carried over from ``docs/TIER_B_MEASUREMENT_CONTRACT.md``:

  - The worst observation is the measurement, never the mean. An operator
    experiences the worst case.
  - A shape that matches nothing is not a measurement. The scan still runs, but
    the per-row comparison work does not, and reporting that as the cost of a
    real query understates it. Every shape asserts a non-empty result.
  - Each observation runs in a fresh subprocess. At ten million rows the
    allocator does not return pages between shapes, so an in-process
    measurement charges one shape's retention to the next.

Growth is the gate, not the constant. A host twice as fast halves every number
here and changes nothing about whether a read is bounded.

  python oms/measure_read_path_bounds.py --sizes 100000,1000000
  python oms/measure_read_path_bounds.py --database-url postgresql+psycopg2://...
"""
from __future__ import annotations

import argparse
import gc
import json
import math
import os
import random
import subprocess
import sys
import tempfile
import time
from pathlib import Path
from typing import Any, Callable, Dict, List, Tuple

REPO_ROOT = Path(__file__).resolve().parent.parent

TYPE_ID = "read_path_asset"
OBJECT_PREFIX = "read_path_object_"

# Matches 1 in 20 rows: selective enough to be a real predicate, common enough
# that the result is never empty at any size.
FILTER_CATEGORY = "category_0"

# --- Spatial distribution -------------------------------------------------
#
# The first version of this fixture placed objects at
# `37.0 + mod(series,1000)/10000` for latitude and the negation of the same
# term for longitude. That is a thousand distinct positions on a single
# diagonal *line*, so ten million objects stacked ten thousand deep at each,
# and a 400 m radius matched 570,000 of them. Every spatial number measured
# against it described the fixture: the query was not finding objects, it was
# scoring a pile of coincident ones.
#
# This places them over an area instead, at two scales, because operational
# assets cluster at sites rather than spreading evenly. Sites are laid out by an
# additive-recurrence (R2) low-discrepancy sequence, which covers a region
# evenly without a random number generator, so the corpus is byte-identical on
# every run and on both dialects. Each object then sits at its own offset within
# its site, so no two objects share a position.
ALPHA_X = 0.7548776662466927   # 1 / plastic number
ALPHA_Y = 0.5698402909980532   # 1 / plastic number squared
REGION_WEST = -122.0
REGION_SOUTH = 37.0
REGION_SPAN_DEGREES = 0.5      # ~55 km x 44 km at this latitude
SITE_COUNT = 2000
SITE_SPREAD_DEGREES = 0.002    # ~200 m, the extent of one site


def _fraction(value: float) -> float:
    return value - math.floor(value)


def position(series: int) -> Tuple[float, float]:
    """The (longitude, latitude) of object `series`. Mirrors the SQL below."""
    site = series % SITE_COUNT
    longitude = (REGION_WEST + _fraction(site * ALPHA_X) * REGION_SPAN_DEGREES
                 + (_fraction(series * ALPHA_Y) * 2 - 1) * SITE_SPREAD_DEGREES)
    latitude = (REGION_SOUTH + _fraction(site * ALPHA_Y) * REGION_SPAN_DEGREES
                + (_fraction(series * ALPHA_X) * 2 - 1) * SITE_SPREAD_DEGREES)
    return longitude, latitude


# Centred on a site rather than an arbitrary point, so the radius and viewport
# shapes are never empty at any cardinality and always describe "the assets at
# this facility" -- the query an operator actually issues.
HUB = position(SITE_COUNT + 7)
RADIUS_METERS = 400.0
# ~550 m by ~440 m: one facility and its immediate surroundings.
VIEWPORT_DEGREES = 0.005

# Bumped whenever the fixture's shape changes, so `--reuse` cannot serve a
# corpus generated by a different definition. Comparing a measurement against
# one taken on a different fixture is the mistake this prevents.
FIXTURE_VERSION = 2

DEFAULT_SIZES = (25_000, 100_000, 400_000)

# Ratchet ceilings from docs/GOAL_2026-08-06.md. Growth is per 10x cardinality.
HEAP_CEILING_MB = 64.0
HEAP_GROWTH_MAX = 1.5
LATENCY_GROWTH_MAX = 2.0

SHAPE_LABELS = [
    "typed read, no filter (the shape the 10M gate measures)",
    "typed read, one equality filter (the Object Explorer)",
    "facet aggregation (the Explorer's left rail)",
    "spatial radius query (the Operational Map)",
    "spatial bbox, map viewport (the B4 gate)",
]


